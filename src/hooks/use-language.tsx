interface LanguageContextType {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, replacements?: { [key: string]: string }) => string;
  availableLanguages: { [key in Language]: string };
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

const availableLanguages: { [key in Language]: string } = {
  en: 'English',
  fr: 'Français',
  es: 'Español',
  pt: 'Português',
  de: 'Deutsch',
  it: 'Italiano',
  ru: 'Русский',
};

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');
  const [isMounted, setIsMounted] = useState(false);

  useEffect(() => {
    setIsMounted(true);
    const storedLanguage = localStorage.getItem('language') as Language | null;
    if (storedLanguage && availableLanguages[storedLanguage]) {
      setLanguageState(storedLanguage);
    } else {
      setLanguageState('en');
    }
  }, []);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if(isMounted) {
      localStorage.setItem('language', lang);
    }
  };

  const t = (key: string, replacements?: { [key: string]: string }): string => {
    if (!isTranslationKey(key)) {
      return key;
    }

    let translation = (translations[language] as any)?.[key] || (translations.en as any)[key];

    if (!translation) return key;

    if (replacements) {
      Object.keys(replacements).forEach(rKey => {
        translation = translation.replace(`{{${rKey}}}`, replacements[rKey]);
      });
    }

    return translation;
  };


  const value = useMemo(() => ({
    language,
    setLanguage,
    t,
    availableLanguages
  // eslint-disable-next-line react-hooks/exhaustive-deps
  }), [language, isMounted]);

  if (!isMounted) {
    return (
      <LanguageContext.Provider value={{ language: 'en', setLanguage: () => {}, t: (key) => key, availableLanguages }}>
        {children}
      </LanguageContext.Provider>
    );
  }

  return React.createElement(LanguageContext.Provider, { value }, children);
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
